package tgbot;

/** Шаг диалога, на котором находится пользователь. */
public enum DialogStep {
    /** Диалог не идёт, бот ждёт команду. */
    IDLE,
    /** Бот ждёт ингредиенты нового рецепта. */
    ADD_INGREDIENTS,
    /** Бот ждёт инструкцию нового рецепта. */
    ADD_INSTRUCTION,
    /** Бот ждёт новое название редактируемого рецепта. */
    EDIT_NAME,
    /** Бот ждёт новые ингредиенты редактируемого рецепта. */
    EDIT_INGREDIENTS,
    /** Бот ждёт новую инструкцию редактируемого рецепта. */
    EDIT_INSTRUCTION
}
